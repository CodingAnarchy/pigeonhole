/// What every request handler shares.
#[derive(Debug)]
pub(crate) struct Shared {
    router: router::Router,
    tokens: auth::Tokens,
    limits: config::Limits,
    metrics: Arc<service::Metrics>,
    /// The feed and feed hub runtimes, once the server has started them: a partition opened
    /// while the node serves runs its feeds there (D317 ticket 6).
    feed_runtimes: std::sync::OnceLock<(tokio::runtime::Handle, tokio::runtime::Handle)>,
}

impl Shared {
    /// The caller an `Authorization` header identifies. With no tokens configured (a
    /// loopback server), everyone may do everything.
    fn caller(&self, header: Option<&str>) -> Result<auth::Caller, errors::ApiError> {
        if !self.tokens.any() {
            return Ok(auth::Caller::anonymous());
        }
        auth::bearer(header)
            .and_then(|t| self.tokens.caller(t))
            .ok_or_else(errors::ApiError::unauthenticated)
    }

    /// Counts a reply to RPC `rpc`, decoded at `started`. A scan's stream is counted by its
    /// task when it ends instead.
    fn count(
        &self,
        rpc: usize,
        started: std::time::Instant,
        reply: &Result<service::ServiceReply, errors::ApiError>,
    ) {
        if let Ok(
            service::ServiceReply::Scan(_)
            | service::ServiceReply::Feed(_)
            | service::ServiceReply::Download(_)
            | service::ServiceReply::Follow(_),
        ) = reply
        {
            return;
        }
        self.metrics.count(
            rpc,
            reply.as_ref().err().map(|e| e.code.as_str()),
            started.elapsed(),
        );
    }
}

/// The tokens from `--token-file` and `PHDB_SERVE_TOKENS`, together.
fn tokens(args: &ServeArgs) -> Result<auth::Tokens, Failure> {
    let file = match &args.token_file {
        Some(path) => Some(
            std::fs::read_to_string(path)
                .map_err(|e| Failure::io(&format!("read {}", path.display()), &e))?,
        ),
        None => None,
    };
    tokens_from(
        file.as_deref(),
        std::env::var("PHDB_SERVE_TOKENS").ok().as_deref(),
    )
}

/// [`tokens`] from the file's text and the variable's, each `None` when not given. A source
/// that is given but holds no token (an empty file, only comments, an empty variable) fails
/// the start: without tokens a loopback server lets every caller do everything, which a
/// named token source never means (audit120's S-S7: a secret mounted empty behind a proxy).
fn tokens_from(file: Option<&str>, env: Option<&str>) -> Result<auth::Tokens, Failure> {
    let mut text = String::new();
    if let Some(f) = file {
        text.push_str(f);
        text.push('\n');
    }
    if let Some(e) = env {
        text.push_str(e);
    }
    let tokens = auth::Tokens::parse(&text, "the tokens").map_err(|e| Failure::usage(&e))?;
    if (file.is_some() || env.is_some()) && !tokens.any() {
        return Err(Failure::usage(
            "--token-file or PHDB_SERVE_TOKENS is set but holds no tokens; a server without \
             tokens lets every caller do everything, so give at least one, or unset both",
        ));
    }
    Ok(tokens)
}

/// `--replica-of`'s settings, with the token from its file or `PHDB_REPLICA_TOKEN`.
fn replica(args: &ServeArgs) -> Result<Option<Arc<replica::Replica>>, Failure> {
    let Some(primary) = &args.replica_of else {
        return Ok(None);
    };
    if !(primary.starts_with("http://") || primary.starts_with("https://")) {
        return Err(Failure::usage(
            "--replica-of is the primary's URL: http://HOST:PORT or https://HOST:PORT",
        ));
    }
    let token = match &args.replica_token_file {
        Some(path) => Some(
            std::fs::read_to_string(path)
                .map_err(|e| Failure::io(&format!("read {}", path.display()), &e))?
                .trim()
                .to_owned(),
        ),
        None => std::env::var("PHDB_REPLICA_TOKEN").ok(),
    }
    .filter(|t| !t.is_empty());
    Ok(Some(replica::Replica::new(replica::ReplicaConfig {
        primary: primary.trim_end_matches('/').to_owned(),
        token,
        run_events: args.replica_run.max(1),
    })))
}

/// The memory store `--memory` names (D313 ticket 8a), with the embedder `--embed-url`
/// gives under `--embed-timeout-ms`, in the slot the service serves it from (#1618).
///
/// A primary opens it now, creating it if missing, as `phdb mcp` would, so a bad pin fails
/// the start. A replica (`writer` false) never creates it: it opens it now only if its copy
/// already has it (so a pin mismatch fails the start too, cli692's D3), and otherwise when a
/// call first needs it. The `--memory-*` creation options are then used only if it's
/// promoted without the store.
///
/// `--embed-local`'s threads run where the network side's do (`placement`), off the shards'
/// CPUs, at most as many as those CPUs (cli692's A2 on #1591).
fn memory(
    args: &ServeArgs,
    db: &pigeonhole::Pigeonhole,
    writer: bool,
    placement: &Arc<placement::Placement>,
    stderr: &mut dyn std::io::Write,
) -> Result<Option<memslot::MemSlot>, Failure> {
    use crate::memcore::{Embedder, LocalPlace};
    let m = &args.memory;
    let Some(name) = &m.memory else {
        return Ok(None);
    };
    let enter = Arc::clone(placement);
    let embedder = Embedder::from_args(
        m,
        Duration::from_millis(args.embed_timeout_ms),
        LocalPlace {
            threads: Some(embed_threads(placement.free_cpus)),
            on_thread_start: Some(Arc::new(move || enter.enter())),
        },
    )?;
    let create = crate::memcore::create_options(m, name);
    let name = args.memory.memory.as_deref().unwrap_or_default();
    // A recall's byte budget: 1 MiB when it sets none, 8 MiB at most, as pages are.
    let (slot, created) = memslot::MemSlot::start(
        db,
        name,
        embedder,
        args.memory.memory_model.as_deref(),
        create,
        (1 << 20, 8 << 20),
        writer,
    )?;
    // An existing store against `--memory-dim` and `--memory-normalization`, as `phdb mcp`
    // checks it: another value fails the start (#1405). A replica that opens the store later
    // checks only its pin, as before.
    if let Some(memslot::Entry::Core(core)) = slot.cached() {
        crate::memcore::check_reopened(m, name, &core)?;
    }
    if created {
        let _ = writeln!(stderr, "phdb serve: memory store {name}: created");
    }
    Ok(Some(slot))
}

/// The startup line's tail when the request runtime's workers also run on the shards' SMT
/// siblings (#1734): `; network threads also on the shards' 4 SMT siblings (4-9,16-25)`,
/// with the workers' whole CPU list.
fn sibling_line(placement: &placement::Placement) -> String {
    match placement.network_cpu_list() {
        Some(cpus) if placement.sibling_cpus > 0 => format!(
            "; network threads also on the shards' {} SMT siblings ({cpus})",
            placement.sibling_cpus
        ),
        _ => String::new(),
    }
}

/// `--embed-local`'s threads on `free` CPUs: `pigeonhole-embed`'s default bound, 4, since one
/// text doesn't split well across more (D318: 32 threads were slower than 4).
fn embed_threads(free: usize) -> usize {
    free.clamp(1, 4)
}

/// With `--embed-local` and the shards pinned (`cpus`, the CPUs left to the network side as a
/// list), a line telling the operator what to export, or `None` once both are set. candle runs
/// large element-wise steps on a process-wide pool of its own, which
/// `LoadOptions::on_thread_start` doesn't reach: `CANDLE_CPU_MASK` places it (Linux) and
/// `CANDLE_NUM_THREADS` sizes it. The mask alone isn't enough: unsized, the pool takes a
/// thread per core (from `RAYON_NUM_THREADS` or the core count) and crowds them onto the
/// masked CPUs (cli692's N2 on #1671). Its size is the embedder's own, `threads`, so
/// embedding takes about that many CPUs in all (N1). Without the mask or `RAYON_NUM_THREADS`,
/// candle 0.11 also re-reads `/proc/cpuinfo` on every matrix product (huggingface/candle#4070).
/// They're read once, from the environment, and setting them here would need `unsafe` (D318),
/// so the operator sets them before the start. Only the unset ones are named.
fn candle_advice(
    cpus: Option<String>,
    threads: usize,
    env: &dyn Fn(&str) -> Option<std::ffi::OsString>,
) -> Option<String> {
    let cpus = cpus?;
    let missing: Vec<String> = [
        ("CANDLE_CPU_MASK", cpus),
        ("CANDLE_NUM_THREADS", threads.to_string()),
    ]
    .into_iter()
    .filter(|(k, _)| env(k).is_none())
    .map(|(k, v)| format!("{k}={v}"))
    .collect();
    if missing.is_empty() {
        return None;
    }
    Some(format!(
        "phdb serve: --embed-local: candle's own thread pool isn't placed and sized off the \
         shards' CPUs. Start the server with these in its environment (they're read once, at \
         start):\n  export {}",
        missing.join(" ")
    ))
}

/// The options every database `serve` opens takes: a single node's and each cluster
/// partition's alike (#1775: a partition had missed `--no-wal-preallocate`'s default, so its
/// logs grew while commits waited on them). Only the shard count, the compaction threads and
/// `--create` are set per database, by [`single_options`] and
/// [`cluster::partition_options`].
pub(crate) fn served_options(cli: &Cli, args: &ServeArgs) -> Options {
    // The server's shard poll (D198 amendment 4): none by default. The logs are sized at
    // start-up, not while commits wait on them (#1621, ICR 0130).
    let mut options = args
        .shard_spin
        .apply(Options::default().wal_preallocate(!args.no_wal_preallocate));
    if let Some(dir) = &cli.shm_dir {
        options = options.shm_dir(dir);
    }
    if let Some(bytes) = args.change_feed {
        options = options.change_feed(pigeonhole::FeedRetention::bytes(bytes));
    }
    options
}

/// A single node's options: [`served_options`], with `--create`, the shard count and the
/// compaction threads.
fn single_options(cli: &Cli, args: &ServeArgs) -> Options {
    let mut options = served_options(cli, args).create_if_missing(args.create);
    // The server's default shard count on every open, a restart's too: the count isn't
    // stored in the file, so without it a reopen took the library's one per core (perf287's
    // g70d on #1697). As a default, not a setting: a change feed's recorded count still
    // wins, since another count would end the feed's history (ICR 0132). `--shards` sets it.
    options = options.default_shards(placement::default_shards());
    if let Some(n) = args.shards {
        options = options.shards(n);
    }
    // Unset, the library's default (D289), which is the same number.
    if let Some(n) = args.compaction_threads {
        options = options.compaction_cores(n);
    }
    options
}

/// Opens the served database, with its engine memory as resolved if `--engine-memory` is set.
fn open(cli: &Cli, args: &ServeArgs) -> Result<(Pigeonhole, Option<placement::Memory>), Failure> {
    let options = single_options(cli, args);
    // `--engine-memory`, for the shard count asked; a database whose change feed recorded
    // another keeps it (ICR 0132), and is reopened with the memory resized for that count
    // (cli692's F2 on #1718).
    let planned = match args.engine_memory {
        Some(total) => {
            let shards = args.shards.unwrap_or_else(placement::default_shards);
            let memory = placement::memory(Some(total), &[(shards, 0)])
                .map_err(|(_, why)| Failure::usage(&format!("--engine-memory: {why}")))?;
            Some(memory[0])
        }
        None => None,
    };
    if !args.create && !args.db_file().exists() {
        return Err(Failure::file_not_found(args.db_file()));
    }
    let open = |memory: Option<placement::Memory>| {
        let o = match memory {
            Some(m) => m.apply(options.clone()),
            None => options.clone(),
        };
        Pigeonhole::open(args.db_file(), o).map_err(|e| Failure::db("open", &e))
    };
    let db = open(planned)?;
    let Some(m) = planned else {
        return Ok((db, None));
    };
    let actual = db.info().map_or(m.shards, |i| i.shards);
    if actual == m.shards {
        return Ok((db, Some(m)));
    }
    let resized = placement::Memory::of(m.bytes(), actual).map_err(|least| {
        Failure::usage(&format!(
            "--engine-memory: the database's change feed keeps {actual} shards, and {} bytes \
             can't cover their memtables: it needs at least {least}",
            m.bytes()
        ))
    })?;
    db.close()
        .map_err(|e| Failure::db("close the database to resize its memory", &e))?;
    Ok((open(Some(resized))?, Some(resized)))
}

async fn shutdown_signal() {
    let ctrl_c = async {
        let _ = tokio::signal::ctrl_c().await;
    };
    #[cfg(unix)]
    let term = async {
        match tokio::signal::unix::signal(tokio::signal::unix::SignalKind::terminate()) {
            Ok(mut s) => {
                s.recv().await;
            }
            Err(_) => std::future::pending::<()>().await,
        }
    };
    #[cfg(not(unix))]
    let term = std::future::pending::<()>();
    tokio::select! {
        () = ctrl_c => {}
        () = term => {}
    }
}

