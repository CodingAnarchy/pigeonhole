/// `phdb serve`.
pub(crate) fn run(
    cli: &Cli,
    args: &ServeArgs,
    stderr: &mut dyn std::io::Write,
) -> Result<ExitStatus, Failure> {
    if let Some(dir) = &args.cluster {
        return cluster::run(cli, args, dir, stderr);
    }
    let tokens = tokens(args)?;
    let tls = match (&args.tls_cert, &args.tls_key) {
        (Some(cert), Some(key)) => {
            Some(tls::acceptor(cert, key).map_err(|e| Failure::usage(&format!("TLS: {e}")))?)
        }
        _ => None,
    };
    config::check_bind(
        args.listen,
        tls.is_some(),
        tokens.any(),
        args.insecure_no_tls_no_auth,
    )
    .map_err(|e| Failure::usage(&e))?;
    if args.insecure_no_tls_no_auth && !args.listen.ip().is_loopback() {
        let _ = writeln!(
            stderr,
            "phdb serve: WARNING: --insecure-no-tls-no-auth: anyone who can reach {} can read and write everything",
            args.listen
        );
    }

    let replica = replica(args)?;
    let (db, engine_memory) = open(cli, args)?;
    if let Some(m) = engine_memory {
        let _ = writeln!(
            stderr,
            "phdb serve: engine memory: {} bytes of memtables ({} per shard, {} shards), a \
             {}-byte block cache and a {}-byte row cache",
            m.memtables(),
            m.memtable_per_shard,
            m.shards,
            m.block_cache,
            m.row_cache
        );
    }
    if replica.is_some() {
        // A bootstrap replaces the file: only a replica's, or an empty one, never a
        // database of its own (a promoted replica restarted with `--replica-of` still set).
        let is_replica = db
            .replicated_seqno()
            .map_err(|e| Failure::db("read the replica's state", &e))?
            .is_some();
        if !is_replica && !db.tables().is_empty() {
            let _ = db.close();
            return Err(Failure::usage(&format!(
                "{} isn't a replica and has tables: --replica-of bootstraps only an empty \
                 database or a replica's (a promoted one is a primary now)",
                args.db_file().display()
            )));
        }
    }
    let placement = Arc::new(placement::Placement::plan(
        &[&db],
        args.io_threads,
        args.blocking_threads,
        args.feed_threads,
        args.feed_hub_threads,
        args.affinity == config::Affinity::On,
    ));
    let limits = args.limits();
    // A cap above half the open-file limit leaves the database too few descriptors: said,
    // not refused (cli692 on #1604).
    if let (Some(max), Some(files)) = (args.max_connections, listener::open_file_limit())
        && u64::try_from(max).unwrap_or(u64::MAX) > files / 2
    {
        let _ = writeln!(
            stderr,
            "phdb serve: --max-connections {max} is above half the open-file limit ({files}): \
             raise ulimit -n, or the server can run out of descriptors for the database"
        );
    }
    let metrics = Arc::new(service::Metrics::default());
    let mut service = service::Service::new(
        db.clone(),
        limits,
        placement.blocking_threads,
        Arc::clone(&metrics),
    )
    .backups(args.backup_dir.as_deref(), args.max_backups)
    .map_err(|e| Failure::usage(&e))?
    // Before `replica`: it rebuilds the indexes, whose rebalancing a replica pauses.
    .placement(&placement)
    .memory_opt(
        memory(args, &db, replica.is_none(), &placement, stderr)?,
        args.memory_calls.unwrap_or(0),
    );
    if let Some(r) = &replica {
        service = service.replica(Arc::clone(r));
    }
    let shared = Arc::new(Shared {
        router: router::Router::single(service),
        tokens,
        limits,
        metrics,
        feed_runtimes: std::sync::OnceLock::new(),
    });

    serve_shared(
        Serving {
            args,
            shared,
            placement,
            tls,
            serving: args.db_file().display().to_string(),
            dbs: vec![db],
            replica,
            start: None,
        },
        stderr,
    )
}

/// What [`serve_shared`] serves.
pub(crate) struct Serving<'a> {
    pub(crate) args: &'a ServeArgs,
    pub(crate) shared: Arc<Shared>,
    pub(crate) placement: Arc<placement::Placement>,
    pub(crate) tls: Option<tokio_rustls::TlsAcceptor>,
    /// What the startup line says is served: the file, or a cluster node's partition.
    pub(crate) serving: String,
    /// The databases to close last: a single node's one, a cluster node's partitions'
    /// (D317 ticket 8a), none on a cluster node that only routes.
    pub(crate) dbs: Vec<Pigeonhole>,
    pub(crate) replica: Option<Arc<replica::Replica>>,
    /// Run on the request runtime once the server listens (a cluster node's map sync).
    pub(crate) start: Option<Box<dyn FnOnce() + Send>>,
}

/// Serves `shared` until a shutdown signal, then shuts down in order: the request runtime,
/// the feed runtime, a bulk load's, the text rebuild's and the vector indexes' threads, and
/// the database last. One copy for a single node and a cluster node (D317 ticket 2,
/// cli692's (a)): the order is subtle.
fn serve_shared(s: Serving<'_>, stderr: &mut dyn std::io::Write) -> Result<ExitStatus, Failure> {
    let Serving {
        args,
        shared,
        placement,
        tls,
        serving,
        dbs,
        replica,
        start,
    } = s;
    let enter = Arc::clone(&placement);
    let unpark = Arc::clone(&placement);
    let runtime = tokio::runtime::Builder::new_multi_thread()
        .worker_threads(placement.io_threads)
        // Tokio's own blocking threads (file I/O, `spawn_blocking`): ours are bounded by the
        // service's semaphore, below this.
        .max_blocking_threads(placement.blocking_threads + 16)
        .thread_name("phdb-serve")
        .on_thread_start(move || enter.enter_network())
        .on_thread_unpark(move || unpark.unpark_network())
        // A mask a partition's open or close published (D317 ticket 6), taken as a worker
        // goes idle too.
        .on_thread_park(placement::refresh)
        .enable_all()
        .build()
        .map_err(|e| Failure::io("start the runtime", &e))?;
    // The change feed's own runtime (ticket 5's (A)): its hubs and its streams' delivery run
    // here, so a put never queues behind them on a request worker. Placed as the network
    // threads are, and named apart so each runtime's CPU can be told apart (perf287's D3).
    // The connection side's framing stays with the connection (D4).
    let enter = Arc::clone(&placement);
    let feed_runtime = tokio::runtime::Builder::new_multi_thread()
        .worker_threads(placement.feed_threads)
        .thread_name("phdb-serve-feed")
        .on_thread_start(move || enter.enter_feed())
        .on_thread_park(placement::refresh)
        .on_thread_unpark(placement::refresh)
        .enable_all()
        .build()
        .map_err(|e| Failure::io("start the feed runtime", &e))?;
    // The hubs' own runtime: each reads its engine feed and fills its ring here, so it never
    // waits behind its clients' delivery or their catch-up reads on the feed runtime (#1397:
    // at 16 hubs × 16 they fell 20 s behind on about 5% of the CPU). A quarter of the feed
    // threads, at least 1, placed with them. A node that only routes has no feeds, and its
    // one hub thread stays idle, as its feed runtime's does.
    let enter = Arc::clone(&placement);
    let hub_runtime = tokio::runtime::Builder::new_multi_thread()
        .worker_threads(placement.hub_threads)
        .thread_name("phdb-serve-hub")
        .on_thread_start(move || enter.enter_hub())
        .on_thread_park(placement::refresh)
        .on_thread_unpark(placement::refresh)
        .enable_all()
        .build()
        .map_err(|e| Failure::io("start the feed hub runtime", &e))?;
    let _ = shared
        .feed_runtimes
        .set((feed_runtime.handle().clone(), hub_runtime.handle().clone()));
    for part in shared.router.parts() {
        part.feeds
            .run_on(feed_runtime.handle().clone(), hub_runtime.handle().clone());
    }

    let served = runtime.block_on(async {
        // SIGUSR1 writes a report of the feed hubs and their clients to stderr (#1397).
        // Node-wide (cli692's Q1 on 8a): every partition's feeds, one after another.
        #[cfg(unix)]
        {
            let feeds: Vec<_> = shared
                .router
                .parts()
                .into_iter()
                .map(|p| Arc::clone(&p.feeds))
                .collect();
            if !feeds.is_empty() {
                tokio::spawn(async move {
                    use tokio::signal::unix::{SignalKind, signal};
                    let Ok(mut usr1) = signal(SignalKind::user_defined1()) else {
                        return;
                    };
                    while usr1.recv().await.is_some() {
                        let f = feeds.clone();
                        let dumped = tokio::task::spawn_blocking(move || {
                            f.iter().map(|f| f.dump()).collect::<String>()
                        });
                        if let Ok(text) = dumped.await {
                            eprint!("{text}");
                        }
                    }
                });
            }
        }
        let listener = tokio::net::TcpListener::bind(args.listen)
            .await
            .map_err(|e| Failure::io(&format!("listen on {}", args.listen), &e))?;
        let addr = listener.local_addr().map_err(|e| Failure::io("listen", &e))?;
        let _ = writeln!(
            stderr,
            "phdb serve: serving {} on {addr} ({}, {}; {} network, {} feed, {} feed hub and {} blocking threads on {} free CPUs, {}{}; {} shard CPUs left out, {} compaction CPUs not)",
            serving,
            if tls.is_some() { "TLS" } else { "no TLS" },
            if shared.tokens.any() { "tokens required" } else { "no tokens" },
            placement.io_threads,
            placement.feed_threads,
            placement.hub_threads,
            placement.blocking_threads,
            placement.free_cpus,
            placement.mode,
            sibling_line(&placement),
            placement.shard_cpus,
            placement.compaction_cpus,
        );
        if let Some(note) = &placement.note {
            let _ = writeln!(stderr, "phdb serve: {note}");
        }
        if args.memory.embed_local
            && let Some(line) = candle_advice(
                placement.cpu_list(),
                embed_threads(placement.free_cpus),
                &|k| std::env::var_os(k),
            )
        {
            let _ = writeln!(stderr, "{line}");
        }
        if let Some(r) = &replica {
            let _ = writeln!(stderr, "phdb serve: a replica of {}", r.primary());
            r.spawn(Arc::clone(&shared));
        }
        if let Some(start) = start {
            start();
        }
        // At the signal, a running bulk load stops at its next message: it takes no more of
        // its stream, then writes and rebalances what it took (the coordinator on #1580).
        let stopping = Arc::clone(&shared);
        let signal = async move {
            shutdown_signal().await;
            for part in stopping.router.parts() {
                part.bulk.stop();
            }
        };
        let bounds = listener::Bounds {
            connections: Arc::clone(&shared.router.service.connections),
            first_byte: shared.limits.request_timeout,
        };
        listener::serve(listener, tls, http::router(Arc::clone(&shared)), signal, Duration::from_millis(args.shutdown_grace_ms), args.http2_send_buffer.map(|n| usize::try_from(n).unwrap_or(usize::MAX)), bounds).await;
        if let Some(r) = &replica {
            r.stop().await;
        }
        Ok::<_, Failure>(())
    });
    runtime.shutdown_timeout(Duration::from_secs(5));
    // The connections are gone, so every client's stream has ended; the hubs end with the
    // runtime, before the database closes under their feeds.
    feed_runtime.shutdown_timeout(Duration::from_secs(5));
    hub_runtime.shutdown_timeout(Duration::from_secs(5));
    // A bulk load's thread, then the vector indexes' rebalancing threads, end before the
    // database closes. The front-ends are gone, so a load's input has ended: it writes what
    // came, and rebalances inline if its index does.
    for part in shared.router.parts() {
        part.bulk.close();
        // A running text rebuild finishes before the database closes (ai1249's S1 on #1587).
        part.texts.close();
        part.indexes.close();
    }
    // A cluster node closes the partitions open now: those it opened while serving too, and
    // not those it closed (D317 ticket 6).
    let dbs: Vec<Pigeonhole> = if shared.router.cluster.is_some() {
        shared.router.parts().iter().map(|p| p.db.clone()).collect()
    } else {
        dbs
    };
    let closed = match dbs.len() {
        0 => {
            let _ = writeln!(stderr, "phdb serve: stopped");
            Ok(())
        }
        n => {
            let _ = writeln!(
                stderr,
                "phdb serve: stopped; closing the database{}",
                if n > 1 { "s" } else { "" }
            );
            // Every one is closed, and the first failure reported (per partition, cli692's
            // Q1 on 8a).
            dbs.into_iter()
                .map(|db| db.close().map_err(|e| Failure::db("close", &e)))
                .fold(Ok(()), Result::and)
        }
    };
    served?;
    closed?;
    Ok(ExitStatus::SUCCESS)
}

