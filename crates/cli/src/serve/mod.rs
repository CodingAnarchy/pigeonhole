/// What every request handler shares.
#[derive(Debug)]
pub(crate) struct Shared {
    router: router::Router,
    tokens: auth::Tokens,
    limits: config::Limits,
    metrics: Arc<service::Metrics>,
}

impl Shared {
    /// The caller an `Authorization` header identifies. With no tokens configured (a
    /// loopback server), everyone may do everything.
    fn caller(&self, header: Option<&str>) -> Result<auth::Caller, errors::ApiError> {
        if !self.tokens.any() {
            return Ok(auth::Caller::anonymous());
        }
        auth::bearer(header)
            .and_then(|t| self.tokens.caller(t))
            .ok_or_else(errors::ApiError::unauthenticated)
    }

    /// Counts a reply to RPC `rpc`, decoded at `started`. A scan's stream is counted by its
    /// task when it ends instead.
    fn count(
        &self,
        rpc: usize,
        started: std::time::Instant,
        reply: &Result<service::ServiceReply, errors::ApiError>,
    ) {
        if let Ok(
            service::ServiceReply::Scan(_)
            | service::ServiceReply::Feed(_)
            | service::ServiceReply::Download(_),
        ) = reply
        {
            return;
        }
        self.metrics.count(
            rpc,
            reply.as_ref().err().map(|e| e.code.as_str()),
            started.elapsed(),
        );
    }
}

/// The tokens from `--token-file` and `PHDB_SERVE_TOKENS`, together.
fn tokens(args: &ServeArgs) -> Result<auth::Tokens, Failure> {
    let mut text = String::new();
    if let Some(path) = &args.token_file {
        text = std::fs::read_to_string(path)
            .map_err(|e| Failure::io(&format!("read {}", path.display()), &e))?;
        text.push('\n');
    }
    if let Ok(env) = std::env::var("PHDB_SERVE_TOKENS") {
        text.push_str(&env);
    }
    auth::Tokens::parse(&text, "the tokens").map_err(|e| Failure::usage(&e))
}

fn open(cli: &Cli, args: &ServeArgs) -> Result<Pigeonhole, Failure> {
    let mut options = Options::default().create_if_missing(args.create);
    // A database this command creates gets the server's default shard count. An existing
    // one keeps its own unless `--shards` says otherwise: an explicit count that differs
    // from the one a change feed recorded would reshard, ending the feed's history.
    match args.shards {
        Some(n) => options = options.shards(n),
        None if !args.file.exists() => options = options.shards(placement::default_shards()),
        None => {}
    }
    if let Some(dir) = &cli.shm_dir {
        options = options.shm_dir(dir);
    }
    if !args.create && !args.file.exists() {
        return Err(Failure::file_not_found(&args.file));
    }
    Pigeonhole::open(&args.file, options).map_err(|e| Failure::db("open", &e))
}

async fn shutdown_signal() {
    let ctrl_c = async {
        let _ = tokio::signal::ctrl_c().await;
    };
    #[cfg(unix)]
    let term = async {
        match tokio::signal::unix::signal(tokio::signal::unix::SignalKind::terminate()) {
            Ok(mut s) => {
                s.recv().await;
            }
            Err(_) => std::future::pending::<()>().await,
        }
    };
    #[cfg(not(unix))]
    let term = std::future::pending::<()>();
    tokio::select! {
        () = ctrl_c => {}
        () = term => {}
    }
}

/// `phdb serve`.
pub(crate) fn run(
    cli: &Cli,
    args: &ServeArgs,
    stderr: &mut dyn std::io::Write,
) -> Result<ExitStatus, Failure> {
    let tokens = tokens(args)?;
    let tls = match (&args.tls_cert, &args.tls_key) {
        (Some(cert), Some(key)) => {
            Some(tls::acceptor(cert, key).map_err(|e| Failure::usage(&format!("TLS: {e}")))?)
        }
        _ => None,
    };
    config::check_bind(
        args.listen,
        tls.is_some(),
        tokens.any(),
        args.insecure_no_tls_no_auth,
    )
    .map_err(|e| Failure::usage(&e))?;
    if args.insecure_no_tls_no_auth && !args.listen.ip().is_loopback() {
        let _ = writeln!(
            stderr,
            "phdb serve: WARNING: --insecure-no-tls-no-auth: anyone who can reach {} can read and write everything",
            args.listen
        );
    }

    let db = open(cli, args)?;
    let placement = Arc::new(placement::Placement::plan(
        &db,
        args.io_threads,
        args.blocking_threads,
        args.feed_threads,
    ));
    let limits = args.limits();
    let metrics = Arc::new(service::Metrics::default());
    let shared = Arc::new(Shared {
        router: router::Router::single(
            service::Service::new(
                db.clone(),
                limits,
                placement.blocking_threads,
                Arc::clone(&metrics),
            )
            .backups(args.backup_dir.as_deref(), args.max_backups)
            .map_err(|e| Failure::usage(&e))?
            .placement(&placement),
        ),
        tokens,
        limits,
        metrics,
    });

    let enter = Arc::clone(&placement);
    let runtime = tokio::runtime::Builder::new_multi_thread()
        .worker_threads(placement.io_threads)
        // Tokio's own blocking threads (file I/O, `spawn_blocking`): ours are bounded by the
        // service's semaphore, below this.
        .max_blocking_threads(placement.blocking_threads + 16)
        .thread_name("phdb-serve")
        .on_thread_start(move || enter.enter())
        .enable_all()
        .build()
        .map_err(|e| Failure::io("start the runtime", &e))?;
    // The change feed's own runtime (ticket 5's (A)): its hubs and its streams' delivery run
    // here, so a put never queues behind them on a request worker. Placed as the network
    // threads are, and named apart so each runtime's CPU can be told apart (perf287's D3).
    // The connection side's framing stays with the connection (D4).
    let enter = Arc::clone(&placement);
    let feed_runtime = tokio::runtime::Builder::new_multi_thread()
        .worker_threads(placement.feed_threads)
        .thread_name("phdb-serve-feed")
        .on_thread_start(move || enter.enter())
        .enable_all()
        .build()
        .map_err(|e| Failure::io("start the feed runtime", &e))?;
    shared
        .router
        .service
        .feeds
        .run_on(feed_runtime.handle().clone());

    let served = runtime.block_on(async {
        let listener = tokio::net::TcpListener::bind(args.listen)
            .await
            .map_err(|e| Failure::io(&format!("listen on {}", args.listen), &e))?;
        let addr = listener.local_addr().map_err(|e| Failure::io("listen", &e))?;
        let _ = writeln!(
            stderr,
            "phdb serve: serving {} on {addr} ({}, {}; {} network, {} feed and {} blocking threads on {} free CPUs, {})",
            args.file.display(),
            if tls.is_some() { "TLS" } else { "no TLS" },
            if shared.tokens.any() { "tokens required" } else { "no tokens" },
            placement.io_threads,
            placement.feed_threads,
            placement.blocking_threads,
            placement.free_cpus,
            placement.mode,
        );
        // At the signal, a running bulk load stops at its next message: it takes no more of
        // its stream, then writes and rebalances what it took (the coordinator on #1580).
        let stopping = Arc::clone(&shared);
        let signal = async move {
            shutdown_signal().await;
            stopping.router.service.bulk.stop();
        };
        listener::serve(listener, tls, http::router(Arc::clone(&shared)), signal, Duration::from_millis(args.shutdown_grace_ms)).await;
        Ok::<_, Failure>(())
    });
    runtime.shutdown_timeout(Duration::from_secs(5));
    // The connections are gone, so every client's stream has ended; the hubs end with the
    // runtime, before the database closes under their feeds.
    feed_runtime.shutdown_timeout(Duration::from_secs(5));
    // A bulk load's thread, then the vector indexes' rebalancing threads, end before the
    // database closes. The front-ends are gone, so a load's input has ended: it writes what
    // came, and rebalances inline if its index does.
    shared.router.service.bulk.close();
    // A running text rebuild finishes before the database closes (ai1249's S1 on #1587).
    shared.router.service.texts.close();
    shared.router.service.indexes.close();
    let _ = writeln!(stderr, "phdb serve: stopped; closing the database");
    let closed = db.close().map_err(|e| Failure::db("close", &e));
    served?;
    closed?;
    Ok(ExitStatus::SUCCESS)
}

